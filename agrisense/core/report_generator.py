"""
AgriSense - Diagnostic & Prescription PDF Report Generator
Generates a formal, printable Agricultural Advisory Report for farmers, agro-retailers, and krishi officers.
Engineered to be 100% portable across Windows, Linux, and Google Colab environments.
"""

import tempfile
import unicodedata
from datetime import datetime
from pathlib import Path
from typing import Dict, Optional

from fpdf import FPDF
from PIL import Image


def sanitize_pdf_text(text: Optional[str]) -> str:
    """
    Sanitize text to Latin-1 range for standard PDF core fonts (Helvetica).
    Converts or removes non-latin characters gracefully to prevent encoding errors on any OS.
    """
    if not text:
        return ""
    # Remove emojis and non-latin characters
    sanitized = ""
    for char in text:
        # Check if character is encodable in latin-1
        try:
            char.encode("latin-1")
            sanitized += char
        except UnicodeEncodeError:
            # Skip or replace with space
            continue
    # Clean up whitespace
    return " ".join(sanitized.split()).strip()


class AgriSensePDF(FPDF):
    """Custom PDF layout with branded green agricultural header and footer."""

    def header(self):
        # Header banner
        self.set_fill_color(34, 112, 62)  # Forest Green
        self.rect(0, 0, 210, 24, "F")
        self.set_font("Helvetica", "B", 14)
        self.set_text_color(255, 255, 255)
        self.set_xy(10, 5)
        self.cell(190, 8, "AgriSense: Explainable Plant Disease Advisory Slip", align="C", ln=True)
        self.set_font("Helvetica", "I", 9)
        self.set_xy(10, 13)
        self.cell(190, 6, "Maharashtra Agricultural Diagnostics System | Pune & Western Ghats Region", align="C", ln=True)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by AgriSense AI Diagnostic Engine | ICAR-MPKV Guidelines", align="C")


def generate_pdf_report(
    crop: str,
    detection_res: Dict,
    treatment_info: Dict,
    weather_info: Dict,
    progression_info: Dict,
    severity_res: Dict,
    original_img: Image.Image,
    gradcam_img: Image.Image,
    farmer_name: str = "Maharashtra Farmer",
    taluka_district: str = "Pune, Maharashtra"
) -> bytes:
    """
    Generate and return bytes of a formal PDF diagnostic slip.
    """
    pdf = AgriSensePDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    clean_farmer = sanitize_pdf_text(farmer_name) or "Maharashtra Farmer"
    clean_district = sanitize_pdf_text(taluka_district) or "Pune, Maharashtra"
    clean_crop = sanitize_pdf_text(crop)

    # 1. Farmer & Inspection Metadata Box
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(33, 37, 41)
    scan_time = datetime.now().strftime("%d-%b-%Y %I:%M %p")

    pdf.set_fill_color(240, 246, 242)
    pdf.set_draw_color(180, 215, 190)
    pdf.rect(10, 28, 190, 22, "DF")

    pdf.set_xy(14, 31)
    pdf.cell(90, 5, f"Farmer / Grower: {clean_farmer}", ln=False)
    pdf.cell(90, 5, f"Date & Time: {scan_time}", ln=True)

    pdf.set_xy(14, 38)
    pdf.cell(90, 5, f"District / Belt: {clean_district}", ln=False)
    pdf.cell(90, 5, f"Crop Type: {clean_crop}", ln=True)

    pdf.ln(8)

    # 2. Diagnostic Summary
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(34, 112, 62)
    pdf.cell(0, 7, "1. DIAGNOSTIC FINDINGS & SEVERITY ASSESSMENT", ln=True)
    pdf.set_draw_color(34, 112, 62)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(3)

    disease_name = sanitize_pdf_text(treatment_info.get("display_name_en", detection_res.get("class_key", "Disease")))
    confidence = detection_res.get("confidence_percent", 0.0)
    severity_level = sanitize_pdf_text(severity_res.get("level", "Mild"))
    affected_area = severity_res.get("affected_percentage", 0.0)
    pathogen = sanitize_pdf_text(treatment_info.get("causal_organism", "Fungal/Bacterial"))

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(20, 20, 20)

    pdf.cell(95, 6, f"Diagnosed Condition: {disease_name}", ln=False)
    pdf.cell(95, 6, f"Confidence Score: {confidence}%", ln=True)

    pdf.cell(95, 6, f"Pathogen: {pathogen}", ln=False)
    pdf.set_font("Helvetica", "B", 10)
    severity_color = (220, 53, 69) if severity_level == "Severe" else (240, 130, 20) if severity_level == "Moderate" else (40, 167, 69)
    pdf.set_text_color(*severity_color)
    pdf.cell(95, 6, f"Severity Stage: {severity_level} ({affected_area}% leaf area)", ln=True)

    pdf.set_text_color(20, 20, 20)
    pdf.set_font("Helvetica", "", 10)
    prog_risk = sanitize_pdf_text(progression_info.get("risk_level", "Moderate"))
    pdf.cell(95, 6, f"Progression Risk: {prog_risk}", ln=True)
    pdf.ln(4)

    # 3. Weather Snapshot
    temp_c = weather_info.get("temperature_c", 27.0)
    humidity = weather_info.get("humidity_percent", 75)
    clean_prog_title = sanitize_pdf_text(progression_info.get("title_en", "Standard Weather Conditions"))
    pdf.set_fill_color(248, 249, 250)
    pdf.set_draw_color(210, 215, 220)
    pdf.rect(10, pdf.get_y(), 190, 12, "DF")
    pdf.set_xy(14, pdf.get_y() + 2)
    pdf.set_font("Helvetica", "I", 9)
    pdf.cell(182, 5, f"Local Microclimate ({clean_district}): Temp: {temp_c}C | Humidity: {humidity}% | {clean_prog_title}", ln=True)
    pdf.ln(5)

    # 4. Embedded Side-by-Side Images (Original Leaf + Grad-CAM Heatmap)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(34, 112, 62)
    pdf.cell(0, 6, "2. VISUAL EXPLAINABILITY (GRAD-CAM FEATURE SALIENCY)", ln=True)
    pdf.ln(1)

    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp_path = Path(tmp_dir)
        orig_file = tmp_path / "orig_leaf.jpg"
        cam_file = tmp_path / "gradcam_leaf.jpg"

        original_img.convert("RGB").save(orig_file, quality=90)
        gradcam_img.convert("RGB").save(cam_file, quality=90)

        img_y = pdf.get_y()
        pdf.image(str(orig_file), x=20, y=img_y, w=65)
        pdf.image(str(cam_file), x=115, y=img_y, w=65)

        pdf.set_xy(20, img_y + 48)
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(100, 100, 100)
        pdf.cell(65, 5, "[A] Original Uploaded Leaf", align="C", ln=False)
        pdf.cell(30, 5, "", ln=False)
        pdf.cell(65, 5, "[B] Grad-CAM CNN Attention Heatmap", align="C", ln=True)

    pdf.set_y(img_y + 55)

    # 5. Localized Chemical & Organic Treatment Prescription
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(34, 112, 62)
    pdf.cell(0, 6, "3. LOCALIZED MAHARASHTRA TREATMENT PRESCRIPTION", ln=True)
    pdf.set_draw_color(34, 112, 62)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(3)

    # Chemical Recommendations Table Header
    pdf.set_fill_color(220, 235, 225)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(20, 60, 30)
    pdf.cell(65, 6, "Chemical / Generic Name", 1, 0, "L", True)
    pdf.cell(50, 6, "Dosage (per Litre Water)", 1, 0, "L", True)
    pdf.cell(40, 6, "Approx Cost (INR)", 1, 0, "C", True)
    pdf.cell(35, 6, "PHI (Safety Days)", 1, 1, "C", True)

    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(30, 30, 30)
    chemicals = treatment_info.get("chemical_treatments", [])
    for c in chemicals[:3]:
        c_name = sanitize_pdf_text(c.get("name", ""))[:36]
        c_dosage = sanitize_pdf_text(c.get("dosage", ""))[:28]
        c_cost = sanitize_pdf_text(c.get("cost_range_inr", ""))
        pdf.cell(65, 6, c_name, 1, 0, "L")
        pdf.cell(50, 6, c_dosage, 1, 0, "L")
        pdf.cell(40, 6, c_cost, 1, 0, "C")
        pdf.cell(35, 6, f"{c.get('phi_days', 0)} Days", 1, 1, "C")

    pdf.ln(3)

    # Organic Alternative
    organics = treatment_info.get("organic_treatments", [])
    if organics:
        top_org = organics[0]
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(40, 100, 40)
        org_name = sanitize_pdf_text(top_org.get("name", ""))
        pdf.cell(0, 5, f"Organic / Bio-control Option: {org_name}", ln=True)
        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(50, 50, 50)
        org_dos = sanitize_pdf_text(top_org.get("dosage", ""))
        org_cost = sanitize_pdf_text(top_org.get("cost_range_inr", ""))
        org_prep = sanitize_pdf_text(top_org.get("prep_instructions", ""))
        pdf.cell(0, 5, f"Dosage: {org_dos} | Cost: {org_cost} | {org_prep}", ln=True)
        pdf.ln(3)

    # 6. Official Disclaimer
    pdf.set_fill_color(254, 243, 240)
    pdf.set_draw_color(230, 180, 170)
    pdf.rect(10, pdf.get_y(), 190, 14, "DF")
    pdf.set_xy(12, pdf.get_y() + 2)
    pdf.set_font("Helvetica", "B", 7)
    pdf.set_text_color(160, 40, 30)
    pdf.cell(186, 4, "STATUTORY ADVISORY DISCLAIMER:", ln=True)
    pdf.set_font("Helvetica", "", 7)
    pdf.set_text_color(80, 80, 80)
    pdf.multi_cell(186, 3, "Pesticide recommendations are based on research advisories from MPKV Rahuri and ICAR-NRC Grapes. Always consult your Taluka Agriculture Officer (Taluka Krishi Adhikari) before large-scale tank spraying. Wear protective equipment (mask, gloves).")

    return bytes(pdf.output())
